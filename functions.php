<?php
    // === АРИФМЕТИЧЕСКИЕ ОПЕРАЦИИ ===
    $x = 10;
    $y = 20;

    echo $x + $y . '<br>';   // 30
    echo $x - $y . '<br>';   // -10
    echo $x * $y . '<br>';   // 200
    echo $x / $y . '<br>';   // 0.5
    echo $x % $y . '<br>';   // 10 (остаток от деления)


    // === ПРИСВАИВАНИЕ С ОПЕРАЦИЕЙ (+=) ===
    $x += 10;   // $x = 20
    $y += 10;   // $y = 30
    echo $x . '<br>';        // 20
    echo $y . '<br>';        // 30


    // === ИНКРЕМЕНТ И ДЕКРЕМЕНТ (++ и --) ===
    $x++;   // $x = 21
    $x--;   // $x = 20


    // === МАТЕМАТИЧЕСКИЕ КОНСТАНТЫ ===
    echo M_PI . '<br>';      // 3.1415926535898
    echo M_E . '<br>';       // 2.718281828459


    // === ВСТРОЕННЫЕ МАТЕМАТИЧЕСКИЕ ФУНКЦИИ ===
    echo abs(2) . '<br>';            // 2 (модуль числа)
    echo ceil(3.2) . '<br>';         // 4 (округление вверх)
    echo floor(3.2) . '<br>';        // 3 (округление вниз)
    echo round(5.634567, 3) . '<br>';// 5.635 (округление до 3 знаков)
    echo mt_rand(1, 20) . '<br>';    // случайное число от 1 до 20


    // === МАКСИМУМ / МИНИМУМ ===
    echo max(4, 5, 6, 7);            // 7 (максимальное число)


    // ============================================================
    // ПОДРОБНЫЙ СПРАВОЧНИК ПО ТОМУ, ЧТО БЫЛО В КОДЕ
    // ============================================================
    
    // ──────────────────────────────────────────────────────────────
    // 1. АРИФМЕТИЧЕСКИЕ ОПЕРАЦИИ
    // ──────────────────────────────────────────────────────────────
    // +   сложение        10 + 20 = 30
    // -   вычитание       10 - 20 = -10
    // *   умножение       10 * 20 = 200
    // /   деление         10 / 20 = 0.5
    // %   остаток         10 % 20 = 10 (остаток от деления)
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 2. ПРИСВАИВАНИЕ С ОПЕРАЦИЕЙ
    // ──────────────────────────────────────────────────────────────
    // $x += 10   →   $x = $x + 10
    // $x -= 10   →   $x = $x - 10
    // $x *= 10   →   $x = $x * 10
    // $x /= 10   →   $x = $x / 10
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 3. ИНКРЕМЕНТ И ДЕКРЕМЕНТ
    // ──────────────────────────────────────────────────────────────
    // $x++   →   $x = $x + 1 (увеличение на 1)
    // $x--   →   $x = $x - 1 (уменьшение на 1)
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 4. МАТЕМАТИЧЕСКИЕ КОНСТАНТЫ
    // ──────────────────────────────────────────────────────────────
    // M_PI   →   3.1415926535898 (число Пи)
    // M_E    →   2.718281828459  (число Эйлера)
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 5. ВСТРОЕННЫЕ МАТЕМАТИЧЕСКИЕ ФУНКЦИИ
    // ──────────────────────────────────────────────────────────────
    // abs(число)        →  модуль числа
    // ceil(число)       →  округление вверх
    // floor(число)      →  округление вниз
    // round(число, n)   →  округление до n знаков
    // mt_rand(от, до)   →  случайное число в диапазоне
    // max(числа)        →  максимальное число
    // min(числа)        →  минимальное число
    // ──────────────────────────────────────────────────────────────


    // ============================================================
    // КРАТКОЕ РЕЗЮМЕ
    // ============================================================
    // 
    // + - * / %   →  основные операции
    // += -= *= /= →  присваивание с операцией
    // ++ --       →  увеличение/уменьшение на 1
    // M_PI M_E    →  математические константы
    // abs() ceil() floor() round() mt_rand() max() min() → функции
    // ============================================================
?>