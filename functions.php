<?php
    // _________________________________________
    // БЛОК 1: Арифметические операции
    // __________________________________________
    $x = 10;
    $y = 20;

    echo $x + $y . '<br>';   // 10 + 20 = 30
    echo $x - $y . '<br>';   // 10 - 20 = -10
    echo $x * $y . '<br>';   // 10 * 20 = 200
    echo $x / $y . '<br>';   // 10 / 20 = 0.5
    echo $x % $y . '<br>';   // 10 % 20 = 10 (остаток от деления)
    // __________________________________________


    // БЛОК 2: Присваивание с операцией (+=)
    // __________________________________________
    $x += 10; // $x = $x + 10; → $x = 20
    $y += 10; // $y = $y + 10; → $y = 30
    echo $x . '<br>';        // 20
    echo $y . '<br>';        // 30
    // __________________________________________


    // БЛОК 3: Инкремент и декремент (++ и --)
    // __________________________________________
    $x++; // $x += 1; → $x = 21
    $x--; // $x -= 1; → $x = 20
    // __________________________________________


    // БЛОК 4: Математические константы
    // __________________________________________
    echo M_PI . '<br>';      // 3.1415926535898
    echo M_E . '<br>';       // 2.718281828459
    // __________________________________________


    // БЛОК 5: Встроенные математические функции
    // __________________________________________
    echo abs(2) . '<br>';            // 2 (модуль числа)
    echo ceil(3.2) . '<br>';         // 4 (округление вверх)
    echo floor(3.2) . '<br>';        // 3 (округление вниз)
    echo round(5.634567, 3) . '<br>';// 5.635 (округление до 3 знаков)
    echo mt_rand(1, 20) . '<br>';    // случайное число от 1 до 20
    // __________________________________________


    // БЛОК 6: Максимум / минимум
    // __________________________________________
    echo max(4, 5, 6, 7);            // 7 (максимальное число)
    // echo min(4, 5, 6, 7);         // 4 (минимальное число)
?>