<?php
    // === ОБЪЯВЛЕНИЕ ПЕРЕМЕННОЙ ===
    $x = 4;


    // === КОНСТРУКЦИЯ SWITCH ===
    switch($x) {
        case 5:
            echo "Var: 5";
            break;
        case 7:
            echo "Var: 7";
            break;
        case 9:
            echo "Var: 9";
            break;
        case 6:
            echo "Var: 6";
            break;
        default:
            echo "Default work!";
            break;
    }


    // ============================================================
    // ПОДРОБНЫЙ СПРАВОЧНИК ПО ТОМУ, ЧТО БЫЛО В КОДЕ
    // ============================================================
    
    // ──────────────────────────────────────────────────────────────
    // 1. КОНСТРУКЦИЯ SWITCH
    // ──────────────────────────────────────────────────────────────
    // switch($переменная) {
    //     case значение1:
    //         код;
    //         break;
    //     case значение2:
    //         код;
    //         break;
    //     default:
    //         код;
    //         break;
    // }
    // 
    // switch проверяет $переменную на равенство с case
    // Если совпало → выполняется код до break
    // default → выполняется, если ни один case не подошел
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 2. BREAK
    // ──────────────────────────────────────────────────────────────
    // break   →  прерывает выполнение switch
    // 
    // Без break код продолжит выполняться до конца:
    // case 5:
    //     echo "5";
    //     // нет break!
    // case 7:
    //     echo "7";
    //     break;
    // // если $x = 5, вывод: "57"
    // 
    // С break:
    // case 5:
    //     echo "5";
    //     break;   // выход
    // case 7:
    //     echo "7";
    //     break;
    // // если $x = 5, вывод: "5"
    // ──────────────────────────────────────────────────────────────


    // ============================================================
    // КРАТКОЕ РЕЗЮМЕ
    // ============================================================
    // 
    // switch($var)   →  проверяет $var на равенство
    // case value:    →  если $var == value
    // break;         →  выход из switch
    // default:       →  если ни один case не подошел
    // 
    // switch лучше, чем много if/elseif для простых сравнений
    // ============================================================
?>