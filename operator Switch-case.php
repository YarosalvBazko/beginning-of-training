<?php
    // _________________________________________
    // БЛОК 1: Объявление переменной
    // _________________________________________
    $x = 4; // Числовая переменная
    // _________________________________________


    // БЛОК 2: Конструкция switch (альтернатива if/elseif)
    // _________________________________________
    switch($x) {
        // Проверяем, равно ли $x числу 5
        case 5:
            echo "Var: 5";   // Если $x == 5, выводим "Var: 5"
            break;           // break - выход из switch (прерывает выполнение)
        
        // Проверяем, равно ли $x числу 7
        case 7:
            echo "Var: 7";   // Если $x == 7, выводим "Var: 7"
            break;           // Выход из switch
        
        // Проверяем, равно ли $x числу 9
        case 9:
            echo "Var: 9";   // Если $x == 9, выводим "Var: 9"
            break;           // Выход из switch
        
        // Проверяем, равно ли $x числу 6
        case 6:
            echo "Var: 6";   // Если $x == 6, выводим "Var: 6"
            break;           // Выход из switch
        
        // default - выполняется, если ни один case не подошел
        default:
            echo "Default work!"; // $x = 4, поэтому выполняется этот блок
            break;                // break не обязателен, но ставится для порядка
    }
    // _________________________________________

    // ИТОГ: $x = 4, не равно ни 5, ни 7, ни 9, ни 6
    // Выполняется default → вывод: Default work!
    // _________________________________________
?>
