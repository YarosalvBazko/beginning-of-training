<?php
$title = "📝 Строки в PHP";
$lead = "Функции для работы со строками: длина, обрезка, регистр, поиск, хеширование.";

require_once "../blocks/header.php";
require_once "../includes/DemoHelper.php";
?>

<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: Длина строки
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как получить длину строки
// ССЫЛКА: https://www.php.net/manual/ru/function.strlen.php
// ============================================================
DemoHelper::show(
    '$str = "Hello World";
    echo strlen($str);',
    'Длина строки (strlen)',
    'Возвращает количество символов в строке'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: Обрезка пробелов
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как удалить пробелы в начале и конце
// ССЫЛКА: https://www.php.net/manual/ru/function.trim.php
// ============================================================
DemoHelper::show(
    '$str = "   some   ";
    echo trim($str);',
    'Удаление пробелов (trim)',
    'Удаляет пробелы в начале и конце строки',
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: Верхний регистр
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как преобразовать в заглавные буквы
// ССЫЛКА: https://www.php.net/manual/ru/function.strtoupper.php
// ============================================================
DemoHelper::show(
    '$str = "hello";
    echo strtoupper($str);',
    'Переобразование в верхний регистр (strtoupper)',
    'Все буквы становятся заглавными'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: Нижний регистр
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как преобразовать в строчные буквы
// ССЫЛКА: https://www.php.net/manual/ru/function.strtolower.php
// ============================================================
DemoHelper::show(
    '$str = "HELLO";
    echo strtolower($str);',
    'Переобразование в нижний регистр (strtolower)',
    'Все буквы становятся строчными'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 5: Поиск подстроки
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как найти позицию подстроки
// ССЫЛКА: https://www.php.net/manual/ru/function.strpos.php
// ============================================================
DemoHelper::show(
    '$str = "Hello World";
    echo strpos($str, "World");',
    'Поиск подстроки (strpos)',
    'Находит позицию первохо вхождения подстроки'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 6: Разделение строки (explode)
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как превратить строку в массив
// ССЫЛКА: https://www.php.net/manual/ru/function.explode.php
// ============================================================
DemoHelper::show(
    '$words = "john,bob,alex";
    $arr = explode(",", $words);
    print_r($arr);',
    'Разделение строки (explode)',
    'Превращает строку в массив по разделителю'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 7: Объединение массива (implode)
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как превратить массив в строку
// ССЫЛКА: https://www.php.net/manual/ru/function.implode.php
// ============================================================
DemoHelper::show(
    '$arr = ["john", "bob", "alex"];
    echo implode(" | ", $arr);',
    'Объединение массива (implode)',
    'Превращает массив в строку с разделителем'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 8: Хеширование (md5)
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как создать хеш
// ССЫЛКА: https://www.php.net/manual/ru/function.md5.php
// ============================================================
DemoHelper::show(
    'echo md5("qwert");',
    'Хеширование (md5)',
    'Создает 32-символьный хеш (необратимое шифрование)'
);
?>


