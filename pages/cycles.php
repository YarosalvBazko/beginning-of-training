$title = "🔄 Циклы в PHP";
$lead = "Циклы for, while, do-while, break, continue..";
$doc_link = 'https://www.php.net/manual/ru/control-structures.for.php';
require_once "../blocks/header.php";
require_once "../includes/DemoHelper.php";
?>

<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: Цикл for
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем цикл со счетчиком от 1 до 5
// ССЫЛКА: https://www.php.net/manual/ru/control-structures.for.php
// ============================================================
DemoHelper::show(
    'for($i = 1; $i <= 5; $i++) {
        echo "Число: $i<br>";
    }',
    'Цикл for',
    'Итерация от 1 до 5 с шагом 1'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: Цикл while
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем цикл с условием
// ССЫЛКА: https://www.php.net/manual/ru/control-structures.while.php
// ============================================================
DemoHelper::show(
    '$i = 1;
    while($i <= 5) {
        echo "Шаг: $i<br>";
        $i++;
    }',
    'Цикл while',
    'Выполняется пока условие истинно'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: Цикл do-while
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем цикл, который выполняется хотя бы 1 раз
// ССЫЛКА: https://www.php.net/manual/ru/control-structures.do.while.php
// ============================================================
DemoHelper::show(
    '$i = 10;
    do {
        echo "Выполнился! i = $i<br>";
    } while($i < 5);',
    'Цикл do-while',
    'Выполняется хотя бы 1 раз, даже если условие ложно'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: break
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как прервать цикл
// ССЫЛКА: https://www.php.net/manual/ru/control-structures.break.php
// ============================================================
DemoHelper::show(
    'for($i = 1; $i <= 10; $i++) {
        if($i == 5) {
            break; // Выход из цикла
        }
        echo "i = $i<br>";
    }',
    'Оператор break',
    'Прерывает выполнение цикла при достижении условия'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 5: continue
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как пропустить итерацию
// ССЫЛКА: https://www.php.net/manual/ru/control-structures.continue.php
// ============================================================
DemoHelper::show(
    'for($i = 1; $i <= 5; $i++) {
        if($i == 3) {
            continue; // Пропускаем итерацию
        }
        echo "i = $i<br>";
    }',
    'Оператор continue',
    'Пропускает текущую итерацию и переходит к следующей'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 6: Перебор массива через foreach
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как перебрать массив
// ССЫЛКА: https://www.php.net/manual/ru/control-structures.foreach.php
// ============================================================
DemoHelper::show(
    '$arr = ["apple", "banana", "orange"];
    foreach($arr as $value) {
        echo "Фрукт: $value<br>";
    }',
    'Перебор массива через foreach',
    'Проходит по всем значениям массива без индексов'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 7: foreach с ключами
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем перебор с ключами и значениями
// ============================================================
DemoHelper::show(
    '$user = ["name" => "Alex", "age" => 25, "city" => "Moscow"];
    foreach($user as $key => $value) {
        echo "$key: $value<br>";
    }',    
    'foreach с ключами',
    'Получаем ключи и значания ассоциативного массива'
);
?>

