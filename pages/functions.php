$title = "⚡ Функции в PHP";
$lead = "Объявление функций, параметры, возврат значений.";
$doc_link = "https://www.php.net/manual/ru/functions.user-defined.php";
require_once "../blocks/header.php";
require_once "../includes/DemoHelper.php";
?>

<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: Простая функция
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем функцию, которая принимает параметр
// ССЫЛКА: https://www.php.net/manual/ru/functions.user-defined.php
// ============================================================
DemoHelper::show(
    'function sayHello($name) {
        echo "Привет, $name!<br>";
    }
    sayHello("Alex");
    sayHello("Maria");',
    'Простая функция',
    'Функция принимает параметр и выводит приветствие'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: Функция с return
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем функцию, которая возвращает значение
// ССЫЛКА: https://www.php.net/manual/ru/functions.returning-values.php
// ============================================================
DemoHelper::show(
    'function add($a, $b) {
        return $a + $b;
    }
    $result = add(5, 7);
    echo "5 + 7 = $result";',
    'Функция с возвратом значения (return)',
    'Функция возвращает результат, который можно использовать в переменной'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: global
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как изменить глобальную переменную
// ССЫЛКА: https://www.php.net/manual/ru/language.variables.scope.php#language.variables.scope.global
// ============================================================
DemoHelper::show(
    '$x = 10;
    
    function changeX() {
        global $x;
        $x = 100;
    }
    
    echo "До: $x<br>";
    changeX();
    echo "После: $x";',
    'Использование global',
    'Функция изменяет глобальную переменную $x'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: static
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как сохранить значение между вызовами
// ССЫЛКА: https://www.php.net/manual/ru/language.variables.scope.php#language.variables.scope.static
// ============================================================
DemoHelper::show(
    'function counter() {
        static $count = 0;
        $count++;
        echo "Вызов #$count<br>";
    }
    
    counter();
    counter();
    counter();',
    'Использование static',
    'Переменная сохраняет значение между вызовами функции'
);
?>

