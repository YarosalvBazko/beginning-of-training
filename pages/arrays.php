<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: Создание массива
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как создать массив с помощью []
// ССЫЛКА: https://www.php.net/manual/ru/language.types.array.php
// ============================================================
DemoHelper::show(
    '$arr = [5, 7, 3, 6, 8];
    print_r($arr);',
    'Создание массива',
    'Массив создается с помощью квадратных скобок []'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: Доступ к элементам
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как получить элемент по индексу
// ССЫЛКА: https://www.php.net/manual/ru/language.types.array.php#language.types.array.syntax.accessing
// ============================================================
DemoHelper::show(
    '$arr = ["apple", "banana", "orange"];
    echo $arr[1];',
    'Доступ к элементу по индексу',
    'Индексы в массиве начинаются с 0'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: Изменение элемента
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как изменить элемент по индексу
// ============================================================
DemoHelper::show(
    '$arr = ["apple", "banana", "orange"];
    $arr[1] = "grape";
    print_r($arr);',
    'Изменение элемента',
    'Присваиваем новое значение элементу по индексу'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: Удаление элемента
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как удалить элемент с помощью unset()
// ССЫЛКА: https://www.php.net/manual/ru/function.unset.php
// ============================================================
DemoHelper::show(
    '$arr = ["apple", "banana", "orange"];
    unset($arr[1]);
    print_r($arr);',
    'Удаление элемента (unset)',
    'После удаления массив становится разреженным'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 5: Переиндексация
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как восстановить индексы после удаления
// ССЫЛКА: https://www.php.net/manual/ru/function.array-values.php
// ============================================================
DemoHelper::show(
    '$arr = ["apple", "banana", "orange"];
    unset($arr[1]);
    $arr = array_values($arr);
    print_r($arr);',
    'Переиндексация (array_values)',
    'Восстанавливаем индексы после удаления'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 6: Сортировка
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как отсортировать массив по убыванию
// ССЫЛКА: https://www.php.net/manual/ru/function.rsort.php
// ============================================================
DemoHelper::show(
    '$arr = [5, 2, 8, 1, 9];
    rsort($arr);
    print_r($arr);',
    'Сортировка по убыванию (rsort)',
    'Сортирует массив в порядке убывания'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 7: Ассоциативный массив
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем массив со строковыми ключами
// ============================================================
DemoHelper::show(
    '$user = ["name" => "Alex", "age" => 25, "city" => "Moscow"];
    echo $user["name"] . " (" . $user["age"] . " лет)";',
    'Ассоциативный массив',
    'Элементы имеют строковые ключи вместо числовых'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 8: Объединение массивов
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как объединить два массива
// ССЫЛКА: https://www.php.net/manual/ru/function.array-merge.php
// ============================================================
DemoHelper::show(
    '$arr1 = [5, 7, 3];
    $arr2 = [8, 9, 10];
    $arr3 = array_merge($arr1, $arr2);
    print_r($arr3);',
    'Объединение массивов (array_merge)',
    'Склеивает два массива в один'
);
// ============================================================
// ДЕМОНСТРАЦИЯ 9: Поиск в массиве
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как найти элемент в массиве
// ССЫЛКА: https://www.php.net/manual/ru/function.in-array.php
// ============================================================
DemoHelper::show(
    '$arr = [5, 7, 3, 6, 8];
    if (in_array(3, $arr)) {
        echo "Элемент 3 найден!";
    } else {
        echo "Элемент 3 не найден";
    }',
    'Поиск элемента (in_array)',
    'Проверяет, есть ли значение в массиве'
);
?>

