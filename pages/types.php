<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: gettype
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как определить тип переменной
// ССЫЛКА: https://www.php.net/manual/ru/function.gettype.php
// ============================================================
DemoHelper::show(
    '$a = 10;
    $b = "Hello";
    $c = true;
    $d = 3.14;
    $e = [1, 2, 3];

    echo "a: " . gettype($a) . "<br>";
    echo "b: " . gettype($b) . "<br>";
    echo "c: " . gettype($c) . "<br>";
    echo "d: " . gettype($d) . "<br>";
    echo "e: " . gettype($e);',
    'Определение типа (gettype)',
    'Возвращает тип переменной: integer, string, boolean, double, array'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: is_numeric
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как проверить, является ли значение числом
// ССЫЛКА: https://www.php.net/manual/ru/function.is-numeric.php
// ============================================================
DemoHelper::show(
    '$a = 10;
    $b = "10";
    $c = "Hello";
    
    echo "a: " . (is_numeric($a) ? "число" : "не число") . "<br>";
    echo "b: " . (is_numeric($b) ? "число" : "не число") . "<br>";
    echo "c: " . (is_numeric($c) ? "число" : "не число");',
    'Проверка на число (is_numeric)',
    'Проверяет, является ли переменая числом или числовой строкой'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: is_integer
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как проверить на целое число
// ССЫЛКА: https://www.php.net/manual/ru/function.is-integer.php
// ============================================================
DemoHelper::show(
    '$a = 10;
    $b = 3.14;
    $c = "10";
    
    echo "a: " . (is_integer($a) ? "целое" : "не целое") . "<br>";
    echo "b: " . (is_integer($b) ? "целое" : "не целое") . "<br>";
    echo "c: " . (is_integer($c) ? "целое" : "не целое");',
    'Проверка на целое число (is_integer)',
    'Проверяет, является ли переменная целым числом'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: is_string
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как проверить на строку
// ССЫЛКА: https://www.php.net/manual/ru/function.is-string.php
// ============================================================
DemoHelper::show(
    '$a = "Hello";
    $b = 10;
    $c = true;
    
    echo "a: " . (is_string($a) ? "строка" : "не строка") . "<br>";
    echo "b: " . (is_string($b) ? "строка" : "не строка") . "<br>";
    echo "c: " . (is_string($c) ? "строка" : "не строка");',
    'Проверка на строку (is_string)',
    'Проверяет, является ли переменная строкой'
);
