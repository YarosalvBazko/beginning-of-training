<?php
$title = "📁 Работа с файлами в PHP";
$lead = "Чтение, запись, проверка существования файлов.";

require_once "../blocks/header.php";
require_once "../includes/DemoHelper.php";
?>

<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: file_exists
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как проверить, существует ли файл
// ССЫЛКА: https://www.php.net/manual/ru/function.file-exists.php
// ============================================================
DemoHelper::show(
    'echo file_exists("../index.php") ? "Файл существует" : "Файл не найден";',
    'Проверка существования (file_exists)',
    'Проверяет, существует ли файл',
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: file_put_contents и file_get_contents
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как записать и прочитать файл
// ССЫЛКА: https://www.php.net/manual/ru/function.file-put-contents.php
// ССЫЛКА: https://www.php.net/manual/ru/function.file-get-contents.php
// ============================================================
DemoHelper::show(
    'file_put_contents("test.txt", "Hello World!");
    echo file_get_contents("test.txt");',
    'Чтение и запись файла',
    'file_put_contents записывает, file_get_contents читает'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: fopen (чтение)
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как открыть файл для чтения
// ССЫЛКА: https://www.php.net/manual/ru/function.fopen.php
// ============================================================
DemoHelper::show(
    '$file = fopen("../index.php", "r");
    if($file) {
        echo "Файл открыт для чтения<br>";
        fclose($file);
        echo "Файл закрыт";
    }',
    'Открытие файла (fopen)',
    'Режим "r" — открыть для чтения'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: fwrite (запись)
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как записать в файл
// ССЫЛКА: https://www.php.net/manual/ru/function.fwrite.php
// ============================================================
DemoHelper::show(
    '$file = fopen("test.txt", "w");
    if($file) {
        fwrite($file, "Новая запись!\n");
        fclose($file);
        echo "Файл перезаписан";
    }',
    'Запись в файл (fwrite)',
    'Режим "w" - открыть для записи (перезаписывает файл)'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 5: __FILE__
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем путь к текущему файлу
// ССЫЛКА: https://www.php.net/manual/ru/language.constants.magic.php
// ============================================================
DemoHelper::show(
    'echo __FILE__;',
    'Путь к текущему файлу (__FILE__)',
    'Показывает полный путь к текущему файлу'
);
?>

