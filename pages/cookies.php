<?php
$title = "🍪 Cookie в PHP";
$lead = "Установка, чтение и удаление cookie.";

require_once "../blocks/header.php";
require_once "../includes/DemoHelper.php";
?>

<?php
// ============================================================
// ДЕМОНСТРАЦИЯ 1: Установка cookie
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как установить cookie
// ССЫЛКА: https://www.php.net/manual/ru/function.setcookie.php
// ============================================================
DemoHelper::show(
    'setcookie("user_name", "Alex", time() + 60);
    echo "Cookie установлена!<br>";
    echo "Имя: user_name<br>";
    echo "Значение: Alex<br>";
    echo "Живет: 60 секунд";',
    'Установка cookie (setcookie)',
    'Сохраняет данные на компьютере пользователя'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 2: Чтение cookie
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как прочитать cookie
// ССЫЛКА: https://www.php.net/manual/ru/reserved.variables.cookies.php
// ============================================================
DemoHelper::show(
    'if(isset($_COOKIE["user_name"])) {
        echo "Привет, " . $_COOKIE["user_name"] . "!";
    } else {
        echo "Cookie не найдена";
    }', 
    'Чтение cookie ($_COOKIE)',
    'Получает значение сохраненной cookie'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 3: Все cookie
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем все cookie
// ============================================================
DemoHelper::show(
    'print_r($_COOKIE);',
    'Просмотр всех cookie (print_r)',
    'Показывает все сохраненные cookie'
);

// ============================================================
// ДЕМОНСТРАЦИЯ 4: Удаление cookie
// ============================================================
// ЧТО ДЕЛАЕМ: Показываем, как удалить cookie
// ============================================================
DemoHelper::show(
    'setcookie("user_name", "", time() - 3600);
    echo "Cookie удалена!<br>";
    echo "Время жизни установлено в прошлом";',
    'Удаление cookie',
    'Устанавливает время жизни в прошлое, чтобы удалить cookie'
);
?>

