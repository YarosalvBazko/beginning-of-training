<?php
    // _________________________________________
    // БЛОК 1: Объявление переменных
    // _________________________________________
    $a = 5;              // Числовая переменная
    $str = "Hello";      // Строковая переменная
    $isWeatherGood = false; // Булевая переменная (true/false)
    // _________________________________________


    // БЛОК 2: Условные операторы (if/elseif/else)
    // _________________________________________
    
    // ВАРИАНТ 1: с оператором ИЛИ (||)
    if($str != "Hello" || $isWeatherGood) {
        // || (ИЛИ) - условие истинно, если ХОТЯ БЫ ОДНО из условий истинно
        // $str != "Hello" → false (строка равна "Hello")
        // $isWeatherGood → false (погода плохая)
        // false || false → false, поэтому этот блок НЕ выполнится
        echo 'First';
    }
    
    // ВАРИАНТ 2: с оператором И (&&) - закомментирован
    // if($str != "Hello" && $isWeatherGood == false) {
    //     // && (И) - условие истинно, только если ОБА условия истинны
    //     // $str != "Hello" → false (строка равна "Hello")
    //     // $isWeatherGood == false → true (погода плохая)
    //     // false && true → false, поэтому этот блок тоже НЕ выполнится
    //     echo 'First';
    // }
    // _________________________________________
    
    
    // БЛОК 3: Второе условие (проверка числа $a)
    // _________________________________________
    else if($a == 5) { 
        // Если $a равно 5 (а это так!)
        $res = "Second";   // Присваиваем значение
        echo $res;         // Выводим: Second

        // ВЛОЖЕННОЕ УСЛОВИЕ: проверяем строку
        if($str == "Hello") { // Если строка равна "Hello" (а это так!)
            echo "<br>Yes";   // Выводим: Yes (с переносом строки)
        }
    } 
    // _________________________________________
    
    
    // БЛОК 4: Остальные условия (не выполнятся, т.к. $a == 5)
    // _________________________________________
    else if($a > 50) {
        // Проверяем, больше ли $a чем 50
        // $a = 5, поэтому условие НЕ выполнится
        echo '$a > 50';
    } else if($a <= 45) {
        // Проверяем, меньше или равно ли $a 45
        // $a = 5, поэтому условие НЕ выполнится (хотя 5 <= 45, но мы уже попали в else if($a == 5))
        echo '$a <= 45';
    } else {
        // Если ни одно условие не подошло (не выполнится)
        echo "Else";
    }
    // _________________________________________

    // ИТОГ: выполнится блок else if($a == 5)
    // Вывод: Second<br>Yes
    // _________________________________________
?>