    ============================================================ -->
    
    <!-- ──────────────────────────────────────────────────────────────
    1. ФУНКЦИЯ date()
    ────────────────────────────────────────────────────────────── -->
    <!-- date(формат, время)  →  форматирует дату и время -->
    <!-- Документация: https://www.php.net/manual/ru/datetime.format.php -->
    <!-- 
    Параметры формата:
    m  →  месяц (01-12)
    d  →  день (01-31)
    l  →  день недели (полное название)
    H  →  час (00-23)
    i  →  минуты (00-59)
    s  →  секунды (00-59)
    
    Примеры:
    date('m-d H:i:s')  →  07-16 15:30:45
    date('Y-m-d')      →  2026-07-16
    date('l')          →  Thursday
    -->
    <!-- ────────────────────────────────────────────────────────────── -->


    <!-- ──────────────────────────────────────────────────────────────
    2. ФУНКЦИЯ time()
    ────────────────────────────────────────────────────────────── -->
    <!-- time()  →  текущая временная метка (Unix timestamp) -->
    <!-- 
    time() + 10800  →  текущее время + 3 часа (10800 секунд)
    -->
    <!-- ────────────────────────────────────────────────────────────── -->


    <!-- ──────────────────────────────────────────────────────────────
    3. ФУНКЦИЯ strtotime()
    ────────────────────────────────────────────────────────────── -->
    <!-- strtotime(строка)  →  преобразует текстовое описание в timestamp -->
    <!-- 
    strtotime("-1 Day +10 Hour")  →  минус 1 день + 10 часов
    strtotime("Last Monday")      →  последний понедельник
    strtotime("+1 Week")          →  через 1 неделю
    strtotime("Next Friday")      →  следующая пятница
    -->
    <!-- ────────────────────────────────────────────────────────────── -->


    <!-- ──────────────────────────────────────────────────────────────
    4. ВРЕМЕННЫЕ ЗОНЫ
    ────────────────────────────────────────────────────────────── -->
    <!-- 
    Для Москвы (UTC+3) добавляем 10800 секунд (3 часа)
    Можно также установить временную зону:
    date_default_timezone_set('Europe/Moscow');
    -->
    <!-- ────────────────────────────────────────────────────────────── -->


