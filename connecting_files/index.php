<?php
    // === РАБОТА С ДАТОЙ И ВРЕМЕНЕМ ===
    // Текущее время + 3 часа (10800 секунд)
    echo date('m-l H:i:s', time() + 10800) . '<br>';
    
    // Время: минус 1 день + 10 часов
    echo date('m-d H:i:s', strtotime("-1 Day +10 Hour")) . '<br>';
    
    // Время последнего понедельника
    echo date('m-d H:i:s', strtotime("Last Monday")) . '<br>';

    // === РАБОТА С МАССИВАМИ ===
    
    // Исходный массив
    $lis = [5, 7, 3, 6, 7, 8];
    
    // unset() - удаляет элемент по индексу
    unset($lis[1]);  // удаляем элемент с индексом 1 (значение 7)
    
    // array_values() - переиндексирует массив (сбрасывает ключи)
    $lis = array_values($lis);
    
    // rsort() - сортирует массив по убыванию
    rsort($lis);
    
    // array_slice() - извлекает срез массива
    // (массив, начальный индекс, длина)
    $arr = array_slice($lis, 2, 2);
    print_r($arr);  // выводит: Array ( [0] => 5 [1] => 3 )
    echo '<br>';

    // === ОБЪЕДИНЕНИЕ МАССИВОВ ===
    $arr_1 = [5, 7];
    $arr_2 = [6, 8, 9];
    
    // array_merge() - объединяет массивы
    $arr_3 = array_merge($arr_1, $arr_2);
    print_r($arr_3);  // выводит: Array ( [0] => 5 [1] => 7 [2] => 6 [3] => 8 [4] => 9 )
    echo '<br>';

    // === ПОИСК В МАССИВЕ ===
    // in_array() - проверяет, существует ли значение в массиве
    if(in_array(3, $lis) == "")
        echo "Not found". '<br>';
    else
        echo "Found". '<br>';
    
    print_r($lis) . '<br>';  // выводит массив после всех операций
    echo '<br>';

    // === ПРОВЕРКА ТИПОВ ===
    $x = 10;
    
    // gettype() - возвращает тип переменной
    echo gettype($x) . '<br>';  // integer
    
    // is_numeric() - проверяет, является ли переменная числом
    echo is_numeric($x) . '<br>';  // 1 (true)
    
    // is_integer() - проверяет, является ли переменная целым числом
    echo is_integer($x) . '<br>';  // 1 (true)

    // === РАБОТА СО СТРОКАМИ ===
    $str = "Example";
    
    // strpos() - позиция первого вхождения подстроки
    echo strpos($str, "am") . '<br>';  // 2 (индекс символа 'a')

    // === РАЗДЕЛЕНИЕ И ОБЪЕДИНЕНИЕ СТРОК ===
    $words = "john,bob,alex";
    
    // explode() - разбивает строку на массив по разделителю
    $arr_words = explode(",", $words);
    print_r($arr_words) . '<br>';  // Array ( [0] => john [1] => bob [2] => alex )
    echo '<br>';
    
    // implode() - объединяет массив в строку с разделителем
    echo implode(" | ", $arr_words);  // john | bob | alex

    // === ПОДКЛЮЧЕНИЕ ПОДВАЛА ===
    require "blocks/footer.php";
?>


