    <!-- 
    gettype($var)    →  возвращает тип переменной
    is_numeric($var) →  проверка на число
    is_integer($var) →  проверка на целое число
    is_string($var)  →  проверка на строку
    is_array($var)   →  проверка на массив
    -->
    <!-- ────────────────────────────────────────────────────────────── -->


