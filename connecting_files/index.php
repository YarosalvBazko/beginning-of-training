    <!-- Документация: https://www.php.net/manual/ru/datetime.format.php -->
    <!-- 
    Параметры формата:
    m  →  месяц (01-12)
    d  →  день (01-31)
    l  →  день недели (полное название)
    H  →  час (00-23)
    i  →  минуты (00-59)
    s  →  секунды (00-59)
    
    Примеры:
    date('m-d H:i:s')  →  07-16 15:30:45
    date('Y-m-d')      →  2026-07-16
    date('l')          →  Thursday
    -->
