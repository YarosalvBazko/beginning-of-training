<?php
    // === ВЫВОД ДАННЫХ ИЗ GET ===
    print_r($_GET);

    // ============================================================
    // ПОДРОБНЫЙ СПРАВОЧНИК ПО ТОМУ, ЧТО БЫЛО В КОДЕ
    // ============================================================
    
    // ──────────────────────────────────────────────────────────────
    // 1. ПОЛУЧЕНИЕ ДАННЫХ ИЗ GET
    // ──────────────────────────────────────────────────────────────
    // $_GET['key']      →  получение данных из URL
    // 
    // Пример: about.php?username=Alex&email=alex@mail.com
    // 
    // print_r($_GET)    →  вывод всех данных из GET
    // 
    // Вывод:
    // Array (
    //     [username] => Alex
    //     [email] => alex@mail.com
    // )
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 2. GET vs POST
    // ──────────────────────────────────────────────────────────────
    // GET  →  данные в URL (видно в адресной строке)
    //        /about.php?username=Alex&email=alex@mail.com
    //        Ограничение по длине ~2048 символов
    //        Не подходит для паролей и личных данных
    // 
    // POST →  данные в теле запроса (не видно в адресной строке)
    //        Нет ограничения по длине
    //        Подходит для паролей и личных данных
    // ──────────────────────────────────────────────────────────────


    // ============================================================
    // КРАТКОЕ РЕЗЮМЕ
    // ============================================================
    // 
    // $_GET        →  данные из URL
    // $_POST       →  данные из формы
    // print_r()    →  вывод массива
    // 
    // GET  →  видно в URL (для поиска, фильтров)
    // POST →  не видно в URL (для паролей, форм)
    // ============================================================
?>