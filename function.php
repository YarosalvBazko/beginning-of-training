<?php
    // === ФУНКЦИЯ ДЛЯ ВЫВОДА ===
    function info($word) {
        echo "$word<br>";
    }

    // === ФУНКЦИЯ СЛОЖЕНИЯ ===
    function math($x, $y) {
        $res = $x + $y;
        return $res;
    }

    $res_1 = math(4, 6);
    $res_2 = math(4, 16);
    info($res_1);   // 10
    info($res_2);   // 20

    // === ФУНКЦИЯ СУММЫ МАССИВА ===
    function summary($arr) {
        $summa = 0;
        foreach($arr as $value) {
            $summa += $value;
        }
        return $summa;
    }

    $list = [5, 7, 3];
    echo summary($list) . "<br>";     // 15
    echo summary([5, 2, 3]) . "<br>"; // 10

    // === ФУНКЦИЯ С GLOBAL (изменяет глобальную переменную) ===
    function info_2() {
        global $x;
        $x = 0;
    }

    $x = 10;
    info_2();
    echo $x . "<br>";   // 0

    // === ФУНКЦИЯ СО STATIC (сохраняет значение между вызовами) ===
    function click() {
        static $count;
        $count++;
        echo $count . "<br>";
    }

    // === ФУНКЦИЯ БЕЗ STATIC (каждый раз создает новую переменную) ===
    function click_2() {
        $count = 0;
        $count++;
        echo $count . "<br>";
    }

    click();   // 1
    click();   // 2
    click();   // 3

    click_2(); // 1
    click_2(); // 1
    click_2(); // 1

