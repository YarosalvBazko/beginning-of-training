<?php
    // _________________________________________
    // БЛОК 1: Работа со строками и вывод
    // _________________________________________
    
    $str = "Hello";
    
    // Двойные кавычки позволяют вставлять переменные прямо в строку
    // . '!' - склеиваем ещё один восклицательный знак через точку
    echo "VAR: $str" . '!'; // Вывод: VAR: Hello!
    
    // Одинарные кавычки НЕ обрабатывают переменные, выведут как есть
    // echo 'VAR: $str'; // выведет: VAR: $str
    
    // Вывод HTML-поля ввода (обратите внимание: tupe - опечатка, должно быть type)
    echo "<input tupe='text'><br>"; // Вывод: <input tupe='text'><br>
    // Правильно: echo "<input type='text'><br>";
    // _________________________________________


    // БЛОК 2: Функции для работы со строками
    // _________________________________________
    
    // strlen() - возвращает длину строки (количество символов)
    $length = strlen($str); // "Hello" = 5 символов
    echo "<br>"; // перенос строки для удобства
    echo "Длина строки: $length<br>"; // Вывод: Длина строки: 5
    
    // trim() - удаляет пробелы в начале и конце строки
    // strtoupper() - преобразует строку в ВЕРХНИЙ РЕГИСТР
    // Внутри: "   some   " -> после trim: "some" -> после strtoupper: "SOME"
    echo strtoupper(trim("   some   ")) . '<br>'; // Вывод: SOME<br>
    
    // Ещё раз выводим длину строки (можно было просто echo $length;)
    echo $length . '<br>'; // Вывод: 5<br>
    // _________________________________________
    
    
    // БЛОК 3: Хеширование (шифрование)
    // _________________________________________
    // md5() - вычисляет MD5-хеш строки (необратимое шифрование)
    // "qwert" -> преобразуется в 32-символьный хеш
    echo md5("qwert"); // Вывод: d8578edf8458ce06fbc5bb76a58c5ca4
    // Это стандартный хеш для строки "qwert"
    
    // _________________________________________
    // ДОПОЛНИТЕЛЬНО: как работает конкатенация
    // _________________________________________
    
    // Вариант 1: через двойные кавычки (интерполяция)
    echo "VAR: $str!"; // Вывод: VAR: Hello!
    
    // Вариант 2: через точку (конкатенация)
    echo 'VAR: ' . $str . '!'; // Вывод: VAR: Hello!
    
    // Вариант 3: смешанный (как у вас)
    echo "VAR: $str" . '!'; // Вывод: VAR: Hello!
?>
