<?php
    // === РАБОТА СО СТРОКАМИ И ВЫВОД ===
    $str = "Hello";
    
    echo "VAR: $str" . '!';   // VAR: Hello!
    echo "<input tupe='text'><br>";


    // === ФУНКЦИИ ДЛЯ РАБОТЫ СО СТРОКАМИ ===
    $length = strlen($str);   // 5
    echo "<br>";
    echo "Длина строки: $length<br>";   // Длина строки: 5
    
    echo strtoupper(trim("   some   ")) . '<br>';   // SOME
    echo $length . '<br>';   // 5


    // === ХЕШИРОВАНИЕ (ШИФРОВАНИЕ) ===
    echo md5("qwert");   // d8578edf8458ce06fbc5bb76a58c5ca4


    // === КОНКАТЕНАЦИЯ (СКЛЕИВАНИЕ) ===
    echo "VAR: $str!";          // VAR: Hello!
    echo 'VAR: ' . $str . '!';  // VAR: Hello!
    echo "VAR: $str" . '!';     // VAR: Hello!


    // ============================================================
    // ПОДРОБНЫЙ СПРАВОЧНИК ПО ТОМУ, ЧТО БЫЛО В КОДЕ
    // ============================================================
    
    // ──────────────────────────────────────────────────────────────
    // 1. КАВЫЧКИ И ВЫВОД
    // ──────────────────────────────────────────────────────────────
    // " "  →  двойные кавычки (обрабатывают переменные)
    // ' '  →  одинарные кавычки (НЕ обрабатывают переменные)
    // 
    // echo "VAR: $str";   →  VAR: Hello (переменная подставлена)
    // echo 'VAR: $str';   →  VAR: $str (переменная НЕ подставлена)
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 2. КОНКАТЕНАЦИЯ (СКЛЕИВАНИЕ)
    // ──────────────────────────────────────────────────────────────
    // .  →  оператор склеивания строк
    // 
    // 'Hello' . ' ' . 'World'   →   'Hello World'
    // 'VAR: ' . $str . '!'      →   'VAR: Hello!'
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 3. ФУНКЦИИ ДЛЯ РАБОТЫ СО СТРОКАМИ
    // ──────────────────────────────────────────────────────────────
    // strlen(строка)       →  длина строки (количество символов)
    // trim(строка)         →  удаляет пробелы в начале и конце
    // strtoupper(строка)   →  преобразует в ВЕРХНИЙ РЕГИСТР
    // strtolower(строка)   →  преобразует в нижний регистр
    // ──────────────────────────────────────────────────────────────


    // ──────────────────────────────────────────────────────────────
    // 4. ХЕШИРОВАНИЕ
    // ──────────────────────────────────────────────────────────────
    // md5(строка)   →  MD5-хеш (32 символа, необратимое шифрование)
    // md5("qwert")  →  d8578edf8458ce06fbc5bb76a58c5ca4
    // ──────────────────────────────────────────────────────────────


    // ============================================================
    // КРАТКОЕ РЕЗЮМЕ
    // ============================================================
    // 
    // " "   →  обрабатывает переменные
    // ' '   →  НЕ обрабатывает переменные
    // .     →  склеивание строк
    // strlen() → длина строки
    // trim()   → удаляет пробелы
    // strtoupper() → в верхний регистр
    // md5()      → хеширование
    // ============================================================
?>
